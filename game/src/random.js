// A small seeded random number generator (mulberry32) plus range helpers. The live game seeds
// it from the clock; the screenshot scenes seed it with a fixed number so the same scene is
// staged identically on every run.

export function makeRng(seed) {
  let state = seed >>> 0;
  const next = () => {
    state = (state + 0x6d2b79f5) >>> 0;
    let t = state;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
  next.range = (min, max) => min + next() * (max - min);
  next.int = (min, max) => Math.floor(next.range(min, max + 1));
  next.chance = (probability) => next() < probability;
  return next;
}
